CREATE TABLE IF NOT EXISTS mail_jobs (
  id VARCHAR(100) PRIMARY KEY,
  attempt_id VARCHAR(36) NOT NULL UNIQUE,
  scenario VARCHAR(30) NOT NULL,
  state VARCHAR(40) NOT NULL DEFAULT 'READY',
  submission_status VARCHAR(40),
  accepted TEXT,
  delivery_action VARCHAR(20),
  delivery_status VARCHAR(20),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS application_events (
  id BIGSERIAL PRIMARY KEY, job_id VARCHAR(100), kind VARCHAR(40) NOT NULL, detail TEXT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS received_reports (
  content_hash VARCHAR(64) PRIMARY KEY, envelope_id TEXT NOT NULL, action VARCHAR(20), status VARCHAR(20),
  received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
